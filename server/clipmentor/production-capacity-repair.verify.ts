import assert from 'node:assert/strict';
import saved from '../../src/clipmentor/fixtures/production-saved-projects-20261028.json';
import type {ProjectDoc} from '../../src/editor/types';
import {pictureRepairWriteError,productionCapacityFacts} from './production-capacity-repair';
import {productionRepairContext} from './production-task';
const doc=structuredClone(saved.cases[0].doc) as unknown as ProjectDoc;
const unit=doc.clipMentorAnalysis!.blueprint[0];
const internal=(unit as unknown as {internal_review:Record<string,any>}).internal_review;
const plan=structuredClone(internal[internal.current_picture_plan]);
const args={action:'set_picture_plan',id:unit.unit_id,record:{plan}};
const groups=[{unit_id:unit.unit_id}];
assert.equal(pictureRepairWriteError(doc,args,groups),undefined);
for(const action of ['set_copy_candidate','revise','set_source_breakdown','append'])assert.match(pictureRepairWriteError(doc,{...args,action},groups)!,/only_set_picture_plan/);
assert.match(pictureRepairWriteError(doc,{...args,id:'another-unit'},groups)!,/affected_unit/);
assert.match(pictureRepairWriteError(doc,{...args,record:{plan:{...plan,delivery_sections:[{line:'changed CTA'}]}}},groups)!,/preserve_delivery/);
assert.match(pictureRepairWriteError(doc,{...args,record:{}},groups)!,/current_plan_missing/);
const before=JSON.stringify(doc),facts=await productionCapacityFacts(doc);
assert.equal(JSON.stringify(doc),before);
assert(facts.length>0);assert(facts.every(f=>Number.isFinite(f.measured_audio_seconds)&&f.registered_dynamic_seconds>=0));
for(const f of facts)assert.equal(f.measured_audio_seconds,f.lines.reduce((n,l)=>n+l.audio.durationSeconds,0));
const context={audio_picture_repair:{groups},pending_review_repair:{reason:'original verdict'},final_feedback:{text:'keep'}};
const next=productionRepairContext(context,{revision:'next'});
assert.deepEqual(next.audio_picture_repair,context.audio_picture_repair);
assert.deepEqual(next.pending_review_repair,context.pending_review_repair);
assert.deepEqual(next.final_feedback,context.final_feedback);
console.log('capacity repair: current saved facts, readonly, unrelated writes/CTA mutation rejected, recovery context retained');
